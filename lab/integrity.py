"""Measure how far the loaded data is from what its schema implies.

    python -m lab.integrity            # prints and writes results/INTEGRITY.md

Two families of check:

  references  every "this id points at a row in that table" in the schema:
              how many rows point at something that is not there.
  counters    every stored total (answer_count, comment_count, tags.count,
              score): how many rows disagree with a recount from the detail rows.
"""
import sys

from .db import ROOT, connect, scalar

# (child table, child column, parent table, declared as)
REFERENCES = [
    ("posts", "owner_user_id", "users", "validated"),
    ("posts", "parent_id", "posts", "validated"),
    ("posts", "accepted_answer_id", "posts", "not valid"),
    ("posts", "last_editor_user_id", "users", "not valid"),
    ("comments", "post_id", "posts", "validated"),
    ("comments", "user_id", "users", "validated"),
    ("votes", "post_id", "posts", "not valid"),
    ("votes", "user_id", "users", "validated"),
    ("badges", "user_id", "users", "not valid"),
    ("post_links", "post_id", "posts", "validated"),
    ("post_links", "related_post_id", "posts", "not valid"),
    ("post_tags", "post_id", "posts", "validated"),
    ("post_tags", "tag_id", "tags", "validated"),
    ("tags", "excerpt_post_id", "posts", "validated"),
    ("tags", "wiki_post_id", "posts", "validated"),
]

# name -> (what is compared, SQL returning (rows checked, rows that disagree))
COUNTERS = {
    "posts.answer_count": ("stored answer count vs answers present", """
        SELECT count(*), count(*) FILTER (WHERE q.answer_count IS DISTINCT FROM coalesce(a.n, 0))
        FROM posts q
        LEFT JOIN (SELECT parent_id, count(*) AS n FROM posts WHERE post_type_id = 2 GROUP BY 1) a ON a.parent_id = q.id
        WHERE q.post_type_id = 1"""),
    "posts.comment_count": ("stored comment count vs comments present", """
        SELECT count(*), count(*) FILTER (WHERE coalesce(p.comment_count, 0) <> coalesce(c.n, 0))
        FROM posts p
        LEFT JOIN (SELECT post_id, count(*) AS n FROM comments GROUP BY 1) c ON c.post_id = p.id"""),
    "tags.count": ("stored tag usage vs questions carrying the tag", """
        SELECT count(*), count(*) FILTER (WHERE t.count <> coalesce(x.n, 0))
        FROM tags t
        LEFT JOIN (SELECT tag_id, count(*) AS n FROM post_tags GROUP BY 1) x ON x.tag_id = t.id"""),
    "posts.score": ("stored score vs up-votes minus down-votes present", """
        SELECT count(*), count(*) FILTER (WHERE p.score <> coalesce(v.s, 0))
        FROM posts p
        LEFT JOIN (SELECT post_id, sum(CASE vote_type_id WHEN 2 THEN 1 WHEN 3 THEN -1 ELSE 0 END) AS s
                   FROM votes GROUP BY 1) v ON v.post_id = p.id
        WHERE p.post_type_id IN (1, 2)"""),
}


def check_references(conn):
    out = []
    for child, col, parent, declared in REFERENCES:
        total, filled, dangling = conn.execute(f"""
            SELECT count(*), count(c.{col}),
                   count(*) FILTER (WHERE c.{col} IS NOT NULL AND p.id IS NULL)
            FROM {child} c LEFT JOIN {parent} p ON p.id = c.{col}""").fetchone()
        out.append({"reference": f"{child}.{col} -> {parent}.id", "rows": total, "filled": filled,
                    "dangling": dangling, "declared": declared})
    return out


def check_counters(conn):
    out = []
    for name, (what, sql) in COUNTERS.items():
        checked, wrong = conn.execute(sql).fetchone()
        out.append({"counter": name, "what": what, "checked": checked, "wrong": wrong})
    return out


def check_constraints(conn):
    """What the catalog says about each foreign key: is it validated or not?"""
    return conn.execute("""
        SELECT conname, convalidated FROM pg_constraint
        WHERE contype = 'f' AND connamespace = 'public'::regnamespace ORDER BY conname""").fetchall()


def markdown(refs, counters, constraints, site_rows) -> str:
    lines = [
        "# Data integrity report",
        "",
        "Generated by `python -m lab.integrity`. Do not edit by hand.",
        "",
        f"Checked against {site_rows:,} loaded rows.",
        "",
        "## References",
        "",
        "\"Dangling\" rows hold an id that matches no row in the table they point at.",
        "",
        "| Reference | Rows | With a value | Dangling | Share of values | Foreign key |",
        "|---|---:|---:|---:|---:|---|",
    ]
    for r in refs:
        share = f"{100 * r['dangling'] / r['filled']:.2f}%" if r["filled"] and r["dangling"] else "0"
        lines.append(f"| `{r['reference']}` | {r['rows']:,} | {r['filled']:,} | {r['dangling']:,} | {share} | {r['declared']} |")
    lines += [
        "",
        "## Stored totals",
        "",
        "| Column | Compared with | Rows checked | Disagree |",
        "|---|---|---:|---:|",
    ]
    for c in counters:
        lines.append(f"| `{c['counter']}` | {c['what']} | {c['checked']:,} | {c['wrong']:,} |")
    lines += ["", "## Foreign keys in the catalog", "", "| Constraint | Validated |", "|---|---|"]
    lines += [f"| `{name}` | {'yes' if ok else 'no (enforced for new rows only)'} |" for name, ok in constraints]
    return "\n".join(lines) + "\n"


def run(write=True, verbose=True):
    with connect() as conn:
        refs = check_references(conn)
        counters = check_counters(conn)
        constraints = check_constraints(conn)
        total = sum(scalar(conn, f"SELECT count(*) FROM {t}") for t in
                    ["users", "posts", "comments", "votes", "badges", "tags", "post_links", "post_tags"])
    problems = [f"{r['reference']} is declared validated but has {r['dangling']:,} dangling rows"
                for r in refs if r["declared"] == "validated" and r["dangling"]]
    text = markdown(refs, counters, constraints, total)
    if verbose:
        print(text)
    if write:
        (ROOT / "results").mkdir(exist_ok=True)
        (ROOT / "results" / "INTEGRITY.md").write_text(text, encoding="utf-8")
    return refs, counters, constraints, problems


if __name__ == "__main__":
    *_, problems = run()
    for p in problems:
        print("PROBLEM:", p)
    sys.exit(1 if problems else 0)
