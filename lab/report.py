"""Write results/results.json, results/RESULTS.md and one plan file per variant."""
import json
import re

from .db import ROOT

RESULTS = ROOT / "results"


def _ms(x: float) -> str:
    if x >= 100:
        return f"{x:,.0f}"
    if x >= 10:
        return f"{x:.1f}"
    return f"{x:.2f}"


def _size(n: float) -> str:
    for unit in ("B", "kB", "MB"):
        if n < 1024:
            return f"{n:.0f} {unit}" if unit != "MB" else f"{n:.1f} MB"
        n /= 1024
    return f"{n:.1f} GB"


def _slug(s: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", s.lower()).strip("_")


def write_results(results, env, runs, merge=False):
    RESULTS.mkdir(exist_ok=True)
    (RESULTS / "plans").mkdir(exist_ok=True)
    path = RESULTS / "results.json"

    if merge and path.exists():
        # A partial run replaces only the experiments it reran.
        old = json.loads(path.read_text(encoding="utf-8"))
        fresh = {e["id"]: e for e in results}
        results = sorted(
            [e for e in old["experiments"] if e["id"] not in fresh] + list(fresh.values()),
            key=lambda e: e["id"],
        )

    for exp in results:
        for v in exp["variants"]:
            text = v.pop("plan_text", None)
            if text is not None:
                (RESULTS / "plans" / f"{exp['id']}__{_slug(v['name'])}.txt").write_text(text + "\n", encoding="utf-8")

    path.write_text(json.dumps({"environment": env, "runs": runs, "experiments": results}, indent=2, default=str),
                    encoding="utf-8")
    (RESULTS / "RESULTS.md").write_text(markdown(results, env, runs), encoding="utf-8")


def markdown(results, env, runs) -> str:
    lines = [
        "# Results",
        "",
        "Generated by `python -m lab.bench`. Do not edit by hand.",
        "",
        f"PostgreSQL {env['server_version']}, database {env['database_size']}, "
        f"shared_buffers {env['shared_buffers']}, work_mem {env['work_mem']}, "
        f"random_page_cost {env['random_page_cost']}, "
        f"max_parallel_workers_per_gather {env['max_parallel_workers_per_gather']}, jit {env['jit']}.",
        "",
        "Rows: " + ", ".join(f"{t} {n:,}" for t, n in env["rows"].items()) + ".",
        "",
        f"Time is the median of {runs} runs after 2 warm-up runs, measured on the client with every row fetched. "
        "Buffers are 8 kB pages touched (cache hits + reads) in one run. "
        "\"Same rows\" compares a hash of the result with the first variant's.",
        "",
    ]
    for exp in results:
        base = exp["variants"][0]
        lines += [f"## {exp['id']}: {exp['title']}", "", exp["question"].strip(), ""]
        lines += ["| Variant | Median ms | vs first | Buffers | Rows | Same rows | Extra storage | Plan |",
                  "|---|---:|---:|---:|---:|---|---:|---|"]
        for v in exp["variants"]:
            ratio = base["median_ms"] / v["median_ms"] if v["median_ms"] else float("inf")
            speed = "-" if v is base else "did not finish" if v["timed_out"] else (f"{ratio:,.0f}x faster" if ratio >= 10 else
                                           f"{ratio:.1f}x faster" if ratio >= 1.05 else
                                           f"{1 / ratio:.1f}x slower" if ratio <= 0.95 else "same")
            same = "-" if v is base or v["timed_out"] else (
                "yes" if v["hash"] == base["hash"] else
                "no, by design" if v["expect"] == "any" else "**no**")
            storage = " + ".join(_size(b) for b in v["object_bytes"].values()) or "-"
            p = v["plan"]
            plan = "; ".join(dict.fromkeys(n for n in p["nodes"] if "Scan" in n))
            extras = []
            if p["heap_fetches"]:
                extras.append(f"{p['heap_fetches']:,} heap fetches")
            if p["temp_blocks"]:
                extras.append(f"spilled {p['temp_blocks']:,} temp blocks")
            if p["workers"]:
                extras.append(f"{p['workers']} workers")
            if p.get("estimate"):
                e = p["estimate"]
                extras.append(f"{e['node']}: planner expected {e['estimated']:,.0f} rows, got {e['actual']:,.0f}")
            if extras:
                plan += " (" + ", ".join(extras) + ")"
            ms = f"> {_ms(v['median_ms'])} (cancelled)" if v["timed_out"] else _ms(v["median_ms"])
            buffers = "-" if v["timed_out"] else f"{p['buffers_hit'] + p['buffers_read']:,}"
            nrows = "-" if v["timed_out"] else f"{v['rows']:,}"
            lines.append(f"| {v['name']} | {ms} | {speed} | {buffers} | {nrows} | {same} | {storage} | {plan} |")
        notes = [f"- *{v['name']}*: {v['note']}" for v in exp["variants"] if v.get("note")]
        lines += [""] + notes + ([""] if notes else [])
    return "\n".join(lines)
